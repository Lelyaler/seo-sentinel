<?php
declare(strict_types=1);

namespace SeoSentinel\Generator;

class WordPressIntegrationGenerator
{
    /**
     * Generate ready-to-paste WordPress snippet for functions.php
     *
     * @param string $url
     * @param array<string, mixed> $schemaData
     * @return array{functions_php_code: string, plugin_code: string}
     */
    public function generate(string $url, array $schemaData): array
    {
        $parsed = parse_url($url);
        $path = trim($parsed['path'] ?? '', '/');
        $slug = $path ? basename($path) : 'front-page';

        $faqJson = $schemaData['faq']['json'] ?? '{}';
        $serviceJson = $schemaData['service']['json'] ?? '{}';

        // 1. functions.php hook
        $fnCode = "/**\n";
        $fnCode .= " * Добавление семантической микроразметки Schema.org (SEO Sentinel)\n";
        $fnCode .= " * Вставьте этот код в functions.php вашей активной темы\n";
        $fnCode .= " */\n";
        $fnCode .= "add_action('wp_head', static function (): void {\n";
        if ($slug === 'front-page') {
            $fnCode .= "    if (!is_front_page()) {\n        return;\n    }\n";
        } else {
            $fnCode .= "    if (!is_page('{$slug}')) {\n        return;\n    }\n";
        }
        $fnCode .= "    ?>\n";
        $fnCode .= "    <!-- Schema.org Service & FAQ generated by SEO Sentinel -->\n";
        $fnCode .= "    <script type=\"application/ld+json\">\n";
        $fnCode .= "    " . str_replace("\n", "\n    ", $serviceJson) . "\n";
        $fnCode .= "    </script>\n";
        $fnCode .= "    <script type=\"application/ld+json\">\n";
        $fnCode .= "    " . str_replace("\n", "\n    ", $faqJson) . "\n";
        $fnCode .= "    </script>\n";
        $fnCode .= "    <?php\n";
        $fnCode .= "});\n";

        // 2. Standalone MU-Plugin format
        $pluginCode = "<?php\n";
        $pluginCode .= "/**\n";
        $pluginCode .= " * Plugin Name: SEO Sentinel Microdata Inserter\n";
        $pluginCode .= " * Description: Автоматическая вставка Schema.org JSON-LD для страницы {$slug}\n";
        $pluginCode .= " * Version: 1.0.0\n";
        $pluginCode .= " * Author: SEO Sentinel\n";
        $pluginCode .= " */\n\n";
        $pluginCode .= "declare(strict_types=1);\n\n";
        $pluginCode .= "if (!defined('ABSPATH')) {\n    exit;\n}\n\n";
        $pluginCode .= $fnCode;

        return [
            'functions_php_code' => $fnCode,
            'plugin_code' => $pluginCode,
        ];
    }
}
